export function pickReminder(date = new Date()): Reminder {
  const start = Date.UTC(2026, 0, 5);   // понедельник
  const week = Math.floor((date.getTime() - start) / (7 * 24 * 3600 * 1000));
  return REMINDERS[((week % REMINDERS.length) + REMINDERS.length) % REMINDERS.length];
}
