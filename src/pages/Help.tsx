/** Мини-разметка: абзацы, списки, шаги, жирный, подсказки */
function inline(t: string): ReactNode[] {
  return t.split(/(\*\*[^*]+\*\*)/g).map((p, i) => (p.startsWith('**') && p.endsWith('**') ? <b key={i}>{p.slice(2, -2)}</b> : <Fragment key={i}>{p}</Fragment>));
}
function Rich({ text }: { text: string }) {
  const blocks = text.trim().split(/\n{2,}/);
  return (
    <>
      {blocks.map((b, i) => {
        const lines = b.split('\n');
        if (lines.every((l) => l.startsWith('> '))) return <p key={i} className="help-tip">{inline(lines.map((l) => l.slice(2)).join(' '))}</p>;
        const head = lines[0] && !/^(- |\d+\. )/.test(lines[0]) ? lines[0] : null;
        const rest = head ? lines.slice(1) : lines;
        if (rest.length && rest.every((l) => l.startsWith('- '))) {
          return <Fragment key={i}>{head ? <p>{inline(head)}</p> : null}<ul>{rest.map((l, j) => <li key={j}>{inline(l.slice(2))}</li>)}</ul></Fragment>;
        }
        if (rest.length && rest.every((l) => /^\d+\. /.test(l))) {
          return <Fragment key={i}>{head ? <p>{inline(head)}</p> : null}<ol className="steps">{rest.map((l, j) => <li key={j}>{inline(l.replace(/^\d+\. /, ''))}</li>)}</ol></Fragment>;
        }
        return <p key={i}>{inline(lines.join(' '))}</p>;
      })}
    </>
  );
}

