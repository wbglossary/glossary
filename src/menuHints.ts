import type { Me } from './api';

/** Пояснения к пунктам меню слева — показываются при наведении. Учитывают роль человека. */
export function menuHint(page: string, me: Me): string {
  const r = me.role;
  switch (page) {
    case 'home':
      return 'Поиск по глоссарию и то, что ждёт именно вас: счётчики задач и недавно добавленные термины.';
    case 'glossary':
      return 'Все действующие термины с переводами. Фильтры по проекту и языку, «Столбцы…» — какие поля показывать, клик по строке — карточка термина.'
        + (r === 'manager' || r === 'owner' || me.is_en_validator ? ' Отметьте строки галочками, чтобы добавить их в проект.' : '');
    case 'work':
      if (r === 'validator') return 'Ваш язык: согласуйте черновики, разбирайте заявки и просьбы «Устарел». Можно отмечать галочками и утверждать сразу несколько.';
      if (r === 'translator') return 'Ваш язык: вписывайте переводы прямо в таблицу — они сохраняются черновиком, валидатор их согласует.';
      if (r === 'contractor') return 'Языки без валидатора: ваши переводы сразу видны в глоссарии со статусом «Без проверки».';
      return 'Рабочая область любого языка — только просмотр: что переведено, что ждёт согласования.';
    case 'propose':
      return r === 'manager'
        ? 'Предложить новый русский термин и выбрать, на какие языки нужен перевод.'
        : 'Новый термин или перевод к существующему. Заявку рассмотрит валидатор вашего языка.';
    case 'my-requests':
      return 'Всё, что вы предлагали, и что с этим стало. Пока заявку не рассмотрели, её можно исправить, а пока по ней не начали работать — отозвать.';
    case 'archive':
      return 'Термины, убранные из глоссария, и отклонённые заявки.' + (r === 'owner' ? ' Отсюда термин можно вернуть.' : '');
    case 'export':
      return 'Скачать глоссарий: файл для Smartcat (.xlsx), TBX и таблицу для просмотра со всеми языками.';
    case 'import':
      return 'Готовые переводы от подрядчиков для сокращённых языков и языков без валидатора: загрузите .xlsx, проверьте совпадения и добавьте в глоссарий.';
    case 'log':
      return 'Кто, что и когда менял. Журнал нельзя изменить или очистить.';
    case 'admin':
      return 'Люди и роли, языки, проекты.';
    case 'feedback':
      return r === 'owner'
        ? 'Вопросы, проблемы и идеи от всех пользователей сайта. Отвечайте прямо здесь.'
        : 'Ваши вопросы, жалобы и идеи о сайте. Ответ появится здесь же.';
    case 'help':
      return 'Как работать с глоссарием в вашей роли.';
    default:
      return '';
  }
}
